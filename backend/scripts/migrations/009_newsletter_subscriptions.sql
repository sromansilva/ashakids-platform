-- V008: suscripciones de boletín con doble confirmación y baja.
-- Ejecutar primero en una base aislada con respaldo; no se ejecuta al arrancar la API.
BEGIN;
SET LOCAL lock_timeout = '5s';

-- Respaldo previo recomendado (ejecutar fuera de esta transacción):
-- pg_dump --format=custom --table=public.suscripciones_boletin <DATABASE_URL> > newsletter-before-008.dump
DO $$
BEGIN
  IF to_regclass('public.suscripciones_boletin') IS NOT NULL AND
     (SELECT count(*) FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'suscripciones_boletin') < 11 THEN
    RAISE EXCEPTION 'Existe public.suscripciones_boletin con un esquema incompatible; revisar antes de adoptar 008';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.suscripciones_boletin (
  id_suscripcion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo varchar(150) NOT NULL,
  estado varchar(10) NOT NULL DEFAULT 'PENDIENTE',
  token_confirmacion_hash varchar(64),
  token_confirmacion_expira timestamptz,
  token_baja_hash varchar(64),
  consentimiento_en timestamptz NOT NULL DEFAULT now(),
  confirmado_en timestamptz,
  baja_en timestamptz,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT suscripciones_boletin_correo_uq UNIQUE (correo),
  CONSTRAINT suscripciones_boletin_correo_normalizado_ck CHECK (correo = lower(correo)),
  CONSTRAINT suscripciones_boletin_estado_ck CHECK (estado IN ('PENDIENTE', 'ACTIVA', 'BAJA')),
  CONSTRAINT suscripciones_boletin_confirm_hash_uq UNIQUE (token_confirmacion_hash),
  CONSTRAINT suscripciones_boletin_baja_hash_uq UNIQUE (token_baja_hash)
);

CREATE INDEX IF NOT EXISTS suscripciones_boletin_estado_idx
  ON public.suscripciones_boletin (estado);
CREATE INDEX IF NOT EXISTS suscripciones_boletin_confirm_expira_idx
  ON public.suscripciones_boletin (token_confirmacion_expira)
  WHERE token_confirmacion_expira IS NOT NULL;

DO $$
BEGIN
  IF (SELECT count(*) FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'suscripciones_boletin') <> 11
     OR NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'public.suscripciones_boletin'::regclass
                      AND conname = 'suscripciones_boletin_estado_ck') THEN
    RAISE EXCEPTION '008 no verificó el esquema esperado de suscripciones_boletin';
  END IF;
END $$;

-- El rol runtime se concede explícitamente por entorno después de revisar RLS.
-- No se otorgan permisos a PUBLIC, anon, authenticated ni service_role.
COMMIT;

