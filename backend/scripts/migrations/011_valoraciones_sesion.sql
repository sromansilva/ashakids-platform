-- Adopción explícita por propietario. Nunca ejecutar al iniciar la API.
BEGIN;
SET LOCAL lock_timeout = '5s';
CREATE TABLE public.valoraciones_sesion (
  id_valoracion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sesion integer NOT NULL UNIQUE REFERENCES public.sesiones(id_sesion),
  id_usuario integer NOT NULL REFERENCES public.usuarios(id_usuario),
  calificacion integer NOT NULL CONSTRAINT valoraciones_calificacion_ck CHECK (calificacion BETWEEN 1 AND 5),
  comentario varchar(1000),
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX valoraciones_usuario_idx ON public.valoraciones_sesion(id_usuario);
CREATE INDEX valoraciones_fecha_idx ON public.valoraciones_sesion(fecha_creacion DESC, id_valoracion DESC);
ALTER TABLE public.valoraciones_sesion ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.valoraciones_sesion FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.valoraciones_sesion_id_valoracion_seq FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON public.valoraciones_sesion FROM %I',r);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.valoraciones_sesion_id_valoracion_seq FROM %I',r);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ashakids_runtime') THEN
    GRANT SELECT, INSERT ON public.valoraciones_sesion TO ashakids_runtime;
    GRANT USAGE ON SEQUENCE public.valoraciones_sesion_id_valoracion_seq TO ashakids_runtime;
    CREATE POLICY valoraciones_runtime_select ON public.valoraciones_sesion FOR SELECT TO ashakids_runtime USING (true);
    CREATE POLICY valoraciones_runtime_insert ON public.valoraciones_sesion FOR INSERT TO ashakids_runtime WITH CHECK (true);
  END IF;
END $$;
COMMIT;
