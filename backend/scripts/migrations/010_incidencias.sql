-- Reportes reales PADRE/TERAPEUTA. Autorización por identidad en FastAPI.
-- Ejecutar explícitamente por propietario; nunca al arrancar la API.
BEGIN;
SET LOCAL lock_timeout = '5s';
CREATE TABLE public.incidencias (
  id_incidencia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  envio_id uuid NOT NULL UNIQUE,
  rol varchar(12) NOT NULL CONSTRAINT incidencias_rol_ck CHECK (rol IN ('PADRE','TERAPEUTA')),
  tipo varchar(30) NOT NULL CONSTRAINT incidencias_tipo_ck CHECK (tipo IN ('Funcional','Visual / Diseño','Carga / Rendimiento','Error de datos','Paciente / Agenda','Otro')),
  titulo varchar(120) NOT NULL CONSTRAINT incidencias_titulo_ck CHECK (char_length(trim(titulo)) BETWEEN 1 AND 120),
  descripcion varchar(600) NOT NULL CONSTRAINT incidencias_descripcion_ck CHECK (char_length(trim(descripcion)) BETWEEN 1 AND 600),
  estado varchar(12) NOT NULL DEFAULT 'NUEVA' CONSTRAINT incidencias_estado_ck CHECK (estado IN ('NUEVA','LEIDA','RESUELTA')),
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX incidencias_id_usuario_idx ON public.incidencias(id_usuario);
CREATE INDEX incidencias_fecha_idx ON public.incidencias(fecha_creacion DESC, id_incidencia DESC);
ALTER TABLE public.incidencias ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.incidencias FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.incidencias_id_incidencia_seq FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON public.incidencias FROM %I',r);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.incidencias_id_incidencia_seq FROM %I',r);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ashakids_runtime') THEN
    GRANT SELECT, INSERT, UPDATE ON public.incidencias TO ashakids_runtime;
    GRANT USAGE ON SEQUENCE public.incidencias_id_incidencia_seq TO ashakids_runtime;
    CREATE POLICY incidencias_runtime_select ON public.incidencias FOR SELECT TO ashakids_runtime USING (true);
    CREATE POLICY incidencias_runtime_insert ON public.incidencias FOR INSERT TO ashakids_runtime WITH CHECK (true);
    CREATE POLICY incidencias_runtime_update ON public.incidencias FOR UPDATE TO ashakids_runtime USING (true) WITH CHECK (true);
  END IF;
END $$;
COMMIT;
