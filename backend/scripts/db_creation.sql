CREATE TABLE public.usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(60) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    codigo_usuario VARCHAR(6) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    password_change_required BOOLEAN NOT NULL DEFAULT false,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX usuarios_codigo_casefold_uq ON public.usuarios (upper(codigo_usuario));

CREATE TABLE public.roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(12) NOT NULL UNIQUE,
    descripcion VARCHAR(150),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.administradores (
    id_administrador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_administradores_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios(id_usuario)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE public.tutores (
    id_tutor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE,
    parentesco VARCHAR(30),
    telefono VARCHAR(12),
    direccion VARCHAR(200),
    CONSTRAINT fk_tutores_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios(id_usuario)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE public.terapeutas (
    id_terapeuta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE,
    especialidad VARCHAR(100),
    anios_experiencia INTEGER,
    idiomas VARCHAR(50),
    descripcion_profesional TEXT,
    CONSTRAINT fk_terapeutas_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios(id_usuario)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_terapeutas_experiencia
        CHECK (anios_experiencia IS NULL OR anios_experiencia >= 0)
);

CREATE TABLE public.usuario_roles (
    id_usuario_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    id_rol INTEGER NOT NULL,
    asignado_por INTEGER,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_usuario_roles_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios(id_usuario)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_usuario_roles_rol
        FOREIGN KEY (id_rol) REFERENCES public.roles(id_rol)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_roles_administrador
        FOREIGN KEY (asignado_por) REFERENCES public.administradores(id_administrador)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_usuario_rol UNIQUE (id_usuario, id_rol)
);

CREATE TABLE public.sesiones_autenticacion (
    id_sesion_auth INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
