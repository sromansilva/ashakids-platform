CREATE TABLE public.perfiles (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL UNIQUE,
    progreso NUMERIC(5,2) NOT NULL DEFAULT 0.0,
    racha_dias INTEGER NOT NULL DEFAULT 0,
    objetivos_totales INTEGER NOT NULL DEFAULT 0,
    objetivos_completados INTEGER NOT NULL DEFAULT 0,
    actividades_desarrolladas_total INTEGER NOT NULL DEFAULT 0,
    sesiones_totales INTEGER NOT NULL DEFAULT 0,
    fecha_ultima_sesion TIMESTAMPTZ,
    experiencia INTEGER NOT NULL DEFAULT 0,
    nivel INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_perfiles_paciente
        FOREIGN KEY (id_paciente) REFERENCES public.pacientes(id_paciente)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE public.logros (
    id_logro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_logro VARCHAR(100) NOT NULL,
    experiencia_logro INTEGER NOT NULL DEFAULT 0,
    requisito_logro TEXT NOT NULL,
    icono_logro VARCHAR(255)
);

CREATE TABLE public.perfil_logros (
    id_perfil_logro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perfil INTEGER NOT NULL,
    id_logro INTEGER NOT NULL,
    fecha_obtencion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_perfil_logros_perfil
        FOREIGN KEY (id_perfil) REFERENCES public.perfiles(id_perfil)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_perfil_logros_logro
        FOREIGN KEY (id_logro) REFERENCES public.logros(id_logro)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_perfil_logro UNIQUE (id_perfil, id_logro)
);

CREATE INDEX idx_perfiles_paciente ON public.perfiles(id_paciente);
CREATE INDEX idx_perfil_logros_perfil ON public.perfil_logros(id_perfil);
CREATE INDEX idx_perfil_logros_logro ON public.perfil_logros(id_logro);


