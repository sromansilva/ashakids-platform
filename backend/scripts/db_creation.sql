  WHERE tipo_cita = 'INTRODUCTORIA' AND estado_reserva IN ('PENDIENTE', 'CONFIRMADA');
CREATE TABLE public.turnos_semanales (
  id_turno integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terapeuta integer NOT NULL REFERENCES public.terapeutas(id_terapeuta) ON DELETE CASCADE,
  dia integer NOT NULL CHECK (dia BETWEEN 0 AND 5),
  hora integer NOT NULL CHECK (hora BETWEEN 8 AND 17),
  UNIQUE (id_terapeuta, dia, hora));
CREATE TABLE public.bloqueos_agenda (
  id_bloqueo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terapeuta integer NOT NULL REFERENCES public.terapeutas(id_terapeuta) ON DELETE CASCADE,
  inicio timestamptz NOT NULL, fin timestamptz NOT NULL,
  CHECK (fin > inicio));
CREATE INDEX bloqueos_terapeuta_inicio_idx ON public.bloqueos_agenda(id_terapeuta, inicio);
ALTER TABLE public.turnos_semanales ENABLE ROW LEVEL SECURITY;
