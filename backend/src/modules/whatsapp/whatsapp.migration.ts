import { pool } from '../../core/database.js';

export async function migrateWhatsApp() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN;');
    // Evita que dos arranques simultáneos choquen al crear los mismos objetos.
    await client.query(`SELECT pg_advisory_xact_lock(hashtext('migrate_whatsapp'));`);

    await client.query(`
      CREATE TABLE IF NOT EXISTS public.whatsapp_conversaciones (
        telefono character varying(20) PRIMARY KEY,
        estado character varying(20) NOT NULL DEFAULT 'INICIO',
        datos jsonb NOT NULL DEFAULT '{}'::jsonb,
        ultimo_mensaje_en timestamp with time zone NOT NULL DEFAULT now(),
        creado_en timestamp with time zone NOT NULL DEFAULT now()
      );
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS public.whatsapp_mensajes_procesados (
        wamid character varying(255) PRIMARY KEY,
        recibido_en timestamp with time zone NOT NULL DEFAULT now()
      );
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS public.solicitudes_acceso_familia (
        id_solicitud integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        telefono character varying(20) NOT NULL,
        nombres character varying(60) NOT NULL,
        apellidos character varying(80) NOT NULL,
        dni character varying(8) NOT NULL,
        email character varying(150) NOT NULL,
        estado character varying(15) NOT NULL DEFAULT 'PENDIENTE',
        consentimiento_en timestamp with time zone NOT NULL,
        id_usuario_creado integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
        revisado_por integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
        revisado_en timestamp with time zone,
        correo_estado character varying(20),
        aviso_whatsapp_estado character varying(30),
        ultimo_mensaje_en timestamp with time zone NOT NULL DEFAULT now(),
        creado_en timestamp with time zone NOT NULL DEFAULT now(),
        CONSTRAINT solicitudes_acceso_familia_estado_ck
          CHECK (estado IN ('PENDIENTE', 'PROCESANDO', 'APROBADA', 'RECHAZADA'))
      );
    `);

    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitudes_acceso_telefono_abierta
        ON public.solicitudes_acceso_familia (telefono)
        WHERE estado IN ('PENDIENTE', 'PROCESANDO');
      CREATE INDEX IF NOT EXISTS idx_solicitudes_acceso_estado
        ON public.solicitudes_acceso_familia (estado, creado_en DESC);
      CREATE INDEX IF NOT EXISTS idx_whatsapp_mensajes_procesados_recibido
        ON public.whatsapp_mensajes_procesados (recibido_en);
    `);

    await client.query('COMMIT;');
  } catch (err) {
    await client.query('ROLLBACK;');
    throw err;
  } finally {
    client.release();
  }
}
