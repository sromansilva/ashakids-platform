import type { PoolClient, QueryResult } from 'pg';

export type DbExecutor = Pick<PoolClient, 'query'>;

export interface RegistrarAuditoriaOptions {
  idUsuarioActor?: number | null;
  tabla: string;
  entidad: string | number;
  accion: string;
  detalle?: Record<string, unknown> | null;
  datosAnteriores?: Record<string, unknown> | null;
  enTransaccion?: boolean;
}

/**
 * Sanitiza cualquier dato antes de persistir en auditoría.
 * NUNCA incluye DNI, contraseñas, tokens ni enlaces de activación.
 * Si incluye un motivo, se transforma a 'motivo registrado'.
 */
export function sanitizeAuditData(data: unknown): unknown {
  if (data === null || data === undefined) return data;
  if (typeof data !== 'object') return data;
  if (Array.isArray(data)) return data.map(sanitizeAuditData);

  const sanitized: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(data as Record<string, unknown>)) {
    const lowerKey = key.toLowerCase();

    // Eliminar DNI, contraseñas, hashes, tokens, URLs y secretos
    if (
      lowerKey === 'dni' ||
      lowerKey.endsWith('_dni') ||
      lowerKey.startsWith('dni_') ||
      lowerKey.includes('password') ||
      lowerKey.includes('hash') ||
      lowerKey.includes('token') ||
      lowerKey.includes('enlace') ||
      lowerKey.includes('activation_url') ||
      lowerKey.includes('activationurl') ||
      lowerKey.includes('secret') ||
      lowerKey.includes('contrasena') ||
      lowerKey.includes('contraseña')
    ) {
      continue;
    }

    // El motivo de rechazo nunca debe exponer el texto sensible ingresado
    if (lowerKey === 'motivo' || lowerKey === 'motivo_rechazo') {
      sanitized[key] = 'motivo registrado';
      continue;
    }

    // Filtrar cadenas que contengan patrones de tokens o URLs de activación
    if (typeof value === 'string') {
      if (/crear-contrasena\?token=/i.test(value) || /bearer\s+/i.test(value) || /token=[a-zA-Z0-9_-]+/i.test(value)) {
        continue;
      }
    }

    if (typeof value === 'object' && value !== null) {
      sanitized[key] = sanitizeAuditData(value);
    } else {
      sanitized[key] = value;
    }
  }
  return sanitized;
}

/**
 * Inserta una fila en public.auditoria_cambios respetando la definición de docker/init.sql:
 * - id_auditoria (GENERATED BY DEFAULT AS IDENTITY)
 * - id_usuario_actor (integer, nullable, FK usuarios.id_usuario)
 * - nombre_tabla (character varying(50) NOT NULL)
 * - nombre_entidad (character varying(50) NOT NULL)
 * - accion (character varying(12) NOT NULL)
 * - datos_anteriores (jsonb)
 * - datos_nuevos (jsonb)
 * - fecha_evento (timestamp with time zone DEFAULT now())
 *
 * Si se ejecuta dentro de transacción (enTransaccion = true), propaga cualquier error.
 * Si se ejecuta fuera de transacción (enTransaccion = false), captura el fallo y registra solo el código de error
 * para evitar tumbar la operación principal.
 */
export async function registrarAuditoria(
  executor: DbExecutor,
  options: RegistrarAuditoriaOptions,
  enTransaccion: boolean = options.enTransaccion ?? false
): Promise<number | null> {
  const isTx = options.enTransaccion ?? enTransaccion;

  try {
    const actor = options.idUsuarioActor ? Number(options.idUsuarioActor) : null;
    const tabla = String(options.tabla).trim().slice(0, 50);
    const entidad = String(options.entidad).trim().slice(0, 50);
    const accion = String(options.accion).trim().slice(0, 12);
    const sanitizedDetalle = options.detalle ? sanitizeAuditData(options.detalle) : null;
    const sanitizedAnteriores = options.datosAnteriores ? sanitizeAuditData(options.datosAnteriores) : null;

    const res: QueryResult<{ id_auditoria: number }> = await executor.query(
      `INSERT INTO public.auditoria_cambios 
        (id_usuario_actor, nombre_tabla, nombre_entidad, accion, datos_anteriores, datos_nuevos, fecha_evento)
       VALUES ($1, $2, $3, $4, $5, $6, NOW())
       RETURNING id_auditoria;`,
      [
        actor,
        tabla,
        entidad,
        accion,
        sanitizedAnteriores ? JSON.stringify(sanitizedAnteriores) : null,
        sanitizedDetalle ? JSON.stringify(sanitizedDetalle) : null,
      ]
    );

    return res?.rows?.[0]?.id_auditoria ? Number(res.rows[0].id_auditoria) : null;
  } catch (error: unknown) {
    if (isTx) {
      throw error;
    }
    const dbError = error as { code?: string; message?: string } | null;
    const errCode = dbError?.code || (error instanceof Error ? error.message : 'UNKNOWN_ERROR');
    console.warn('[AuditService] Error al registrar auditoría (operación no interrumpida):', errCode);
    return null;
  }
}
