test('validación conserva las reglas anteriores y exige recurso exclusivo para solicitud', async () => {
  const client = { query: async () => ({ rows: [], rowCount: 0 }) };
  const base = { userId: 1, title:'Aviso', text:'Texto', eventKey:'test' };
  for (const invalid of [
    { ...base, type:'SOLICITUD_ACCESO', preference:null, reservationId:1 },
    { ...base, type:'SOLICITUD_ACCESO', preference:'mensajes', solicitudId:1 },
    { ...base, type:'SOLICITUD_ACCESO', preference:null, solicitudId:1, conversationId:1 },
    { ...base, type:'MENSAJE', preference:'mensajes', solicitudId:1 },
    { ...base, type:'NUEVA_CITA', preference:null, reservationId:1 },
  ]) await assert.rejects(() => emitNotificationEvent(client as never, invalid as never), /no coinciden/);
  await emitNotificationEvent(client as never, { ...base, type:'SOLICITUD_ACCESO', preference:null, solicitudId:1 });
  await emitNotificationEvent(client as never, { ...base, type:'MENSAJE', preference:'mensajes', conversationId:1 });
  await emitNotificationEvent(client as never, { ...base, type:'NUEVA_CITA', preference:'nueva_cita', reservationId:1 });
});
