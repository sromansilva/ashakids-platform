"""Derive responsive static WebP assets; preserve every original PNG and alpha."""
from pathlib import Path
from PIL import Image
import hashlib,json
ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'frontend/public/illustrations'
dest=source/'optimized';dest.mkdir(exist_ok=True)
assets={};details=[]
for p in sorted(source.glob('*.png')):
    if p.stem=='mundo-hero-v54':continue # independent hero is no longer rendered
    im=Image.open(p).convert('RGBA')
    widths=[960,1440,1920] if p.stem=='ashi-hero-v1' else [320,640]
    variants=[]
    for width in sorted(set(min(w,im.width) for w in widths)):
        size=(width,round(im.height*width/im.width))
        scaled=im.resize(size,Image.Resampling.LANCZOS)
        import io
        buf=io.BytesIO();scaled.save(buf,format='WEBP',quality=90,method=6)
        data=buf.getvalue();digest=hashlib.sha256(data).hexdigest()[:10]
        name=f'{p.stem}-{width}-{digest}.webp';(dest/name).write_bytes(data)
        variants.append({'src':f'/illustrations/optimized/{name}','width':width,'bytes':len(data)})
    assets[f'/illustrations/{p.name}']={'src':variants[-1]['src'],'srcSet':', '.join(f'{v["src"]} {v["width"]}w' for v in variants),'width':im.width,'height':im.height}
    details.append({'original':p.name,'originalBytes':p.stat().st_size,'variants':variants})
(ROOT/'frontend/src/components/illustrations/publicAssets.ts').write_text('/* Generated by tools/images/optimize_public.py; originals retained. */\nexport const publicAssets: Record<string, {src: string; srcSet: string; width: number; height: number}> = '+json.dumps(assets,indent=2)+';\n',encoding='utf-8')
out=ROOT/'docs/evidence/landing-v56';out.mkdir(exist_ok=True)
(out/'image-optimization.json').write_text(json.dumps(details,indent=2),encoding='utf-8')
print(f'{len(details)} original resources, {sum(d["originalBytes"] for d in details)} original bytes; {sum(d["variants"][-1]["bytes"] for d in details)} bytes for largest WebP variants')
