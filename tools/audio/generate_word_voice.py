"""Author-time generation only; not a runtime dependency. Public editorial text only."""
import asyncio
import hashlib
import json
from pathlib import Path
import edge_tts

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'frontend/public/words/voice/v106'
VOICE = 'es-PE-CamilaNeural'

async def main():
    clips = json.loads((ROOT / 'tmp/voice-v106/texts.json').read_text(encoding='utf-8'))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    lock = asyncio.Semaphore(3)
    async def generate(clip):
        target = OUTPUT / clip['file']
        if target.exists() and target.stat().st_size > 1000:
            return
        async with lock:
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(clip['text'], VOICE, rate='-8%', volume='-8%').save(str(target))
                    if target.stat().st_size < 1000:
                        raise RuntimeError('Empty audio')
                    return
                except Exception:
                    if attempt == 2:
                        raise
                    await asyncio.sleep(2 * (attempt + 1))
    await asyncio.gather(*(generate(clip) for clip in clips))
    manifest = {'voice': VOICE, 'rate': '-8%', 'volume': '-8%', 'entries': {clip['key']: clip['file'] for clip in clips}}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    index = ROOT / 'frontend/src/pages/padre/Sessions/WordGames/wordVoiceIndex.ts'
    index.write_text('// Generated by tools/audio/generate_word_voice.py. Public game text only.\n'
                     + 'export const wordVoiceFiles: Record<string, string> = '
                     + json.dumps(manifest['entries'], ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    evidence = [{'file': clip['file'], 'text': clip['text'], 'bytes': (OUTPUT / clip['file']).stat().st_size,
                 'sha256': hashlib.sha256((OUTPUT / clip['file']).read_bytes()).hexdigest()} for clip in clips]
    evidence_path = ROOT / 'docs/evidence/voice-v106'
    evidence_path.mkdir(parents=True, exist_ok=True)
    (evidence_path / 'clips.json').write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'PASS: {len(clips)} MP3 generated; {sum(clip["bytes"] for clip in evidence)} bytes')

if __name__ == '__main__':
    asyncio.run(main())
